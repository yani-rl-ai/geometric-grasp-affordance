#!/usr/bin/env python3
"""
Regenerates the result tables of the paper (and the ablation / replicate / latency tables) from the per-trial
logs, so every number in the paper can be traced to results/paper_runs/<run>/trials.csv.

    python make_results_tables.py                       # reads results/paper_runs, writes results/results_tables.md
    python make_results_tables.py --runs-dir pose_eval_runs --out my_tables.md     # your own re-run

Table ids: R1 seed-1 main run | R2 seed-2 replicate | R3 both seeds pooled (paper Table VI) | R4 detection |
R5 region-centre error (paper Table V) | R6 ablations (paper Table VII uses rows A, D, E) |
R7 frozen vs no-bias, both seeds | R8 latency (paper Table VIII).
"""
import argparse
import csv
import os

import numpy as np

R = "results/paper_runs"
OBJ = ["cracker_box", "mustard_bottle", "mug", "banana", "tennis_ball"]
POSE = ["P0", "P1", "P2", "P3"]


def load(*runs):
    rows = []
    for r in runs:
        rows += list(csv.DictReader(open(f"{R}/{r}/trials.csv")))
    return rows


def wil(k, n, z=1.96):
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * np.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return round(100 * (c - h)), round(100 * (c + h))


def ok(rows, **f):
    s = [r for r in rows if all(r[k] == v for k, v in f.items())]
    return sum(r["success"] == "True" for r in s), len(s)


def cell(k, n):
    return f"{k}/{n}"


def full(k, n):
    lo, hi = wil(k, n)
    return f"{k}/{n} ({100 * k / n:.1f}%, CI {lo}-{hi}%)"


def grid(rows, title, with_ci_total=True):
    out = [f"### {title}", "", "| Object | P0 | P1 | P2 | P3 | All placements |", "|---|---|---|---|---|---|"]
    for o in OBJ:
        cs = [ok(rows, object=o, scenario=p) for p in POSE]
        k, n = ok(rows, object=o)
        out.append(f"| {o} | " + " | ".join(cell(*c) for c in cs) + f" | {full(k, n) if with_ci_total else cell(k, n)} |")
    cs = [ok(rows, scenario=p) for p in POSE]
    k, n = ok(rows)
    out.append("| **All objects** | " + " | ".join(full(*c) if with_ci_total else cell(*c) for c in cs) + f" | **{full(k, n)}** |")
    return "\n".join(out) + "\n"


ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
ap.add_argument("--runs-dir", default=R)
ap.add_argument("--out", default="results/results_tables.md")
_a = ap.parse_args()
R, OUT = _a.runs_dir, _a.out
os.makedirs(os.path.dirname(OUT) or ".", exist_ok=True)

main1, main2 = load("main"), load("confirm_main_seed2")
nb1, nb2 = load("abl_no_bias"), load("confirm_nobias_seed2")
md = ["# Result tables (generated by make_results_tables.py from results/paper_runs/*/trials.csv)",
      "Success = object reference point >= 5 cm above its resting height AND still >= 5 cm after a 2.0 s hold AND finger contact at the end. Wilson 95% CIs.",
      "Table ids: R1 seed 1, R2 seed 2, R3 pooled (paper Table VI), R4 detection, R5 centre error (Table V), R6 ablations (Table VII), R7 A vs E, R8 latency (Table VIII).", ""]
md += ["## R1  Main run, seed 1 (frozen configuration)", grid(main1, "success per object x placement (5 trials each)", False)]
md += ["## R2  Replicate, seed 2 (same configuration, new seeds)", grid(main2, "success per object x placement (5 trials each)", False)]
md += ["## R3  Both seeds pooled (10 trials per object x placement)", grid(main1 + main2, "success per object x placement")]
md += ["## R4  Detection of the target object (both seeds pooled; detected / 10)", ""]
md += ["| Object | P0 | P1 | P2 | P3 | All |", "|---|---|---|---|---|---|"]
allm = main1 + main2
for o in OBJ:
    c = [sum(r["detected"] == "True" for r in allm if r["object"] == o and r["scenario"] == p) for p in POSE]
    md.append(f"| {o} | " + " | ".join(f"{x}/10" for x in c) + f" | {sum(c)}/40 |")
c = [sum(r["detected"] == "True" for r in allm if r["scenario"] == p) for p in POSE]
md.append("| **All** | " + " | ".join(f"{x}/50" for x in c) + f" | **{sum(c)}/200** |\n")

md += ["## R5  Perceived region centre vs true object position (both seeds pooled, detected trials, mm)", "",
       "| Object | mean | p95 | n |", "|---|---|---|---|"]
for o in OBJ:
    e = np.array([float(r["xy_err_mm"]) for r in allm if r["object"] == o and r["xy_err_mm"] not in ("", None)])
    md.append(f"| {o} | {e.mean():.1f} | {np.percentile(e, 95):.1f} | {len(e)} |")
e = np.array([float(r["xy_err_mm"]) for r in allm if r["xy_err_mm"] not in ("", None)])
md.append(f"| **all** | {e.mean():.1f} (median {np.median(e):.1f}) | {np.percentile(e, 95):.1f} | {len(e)} |\n")

abl = [("A  frozen (DBL-GNG, b=10 mm, depth 55 mm, perceived xy)", "main"), ("B  A with ground-truth xy (oracle)", "abl_oracle_xy"),
       ("C  A with the earlier batch GNG (same parameters)", "abl_legacy_gng"), ("D  raw mask points, no graph, no bias", "abl_raw_points"),
       ("E  A without width bias (b=0)  [post hoc]", "abl_no_bias"),
       ("F  earlier configuration (earlier GNG, oracle xy, 5 mm depth, 15 mm bias, old per-object overrides)", "abl_previous_config"),
       ("G  A with local-slice grasp centre  [post hoc]", "posthoc_local_center"), ("H  A with finger servo kp = 45000  [post hoc]", "posthoc_kp45000")]
md += ["## R6  Ablations, seed 1 (100 trials each)", "",
       "| Configuration | cracker | bottle | mug | banana | ball | P0 | P1 | P2 | P3 | **Total** |", "|---|---|---|---|---|---|---|---|---|---|---|"]
for name, run in abl:
    rows = load(run)
    ko = [ok(rows, object=o)[0] for o in OBJ]
    kp = [ok(rows, scenario=p)[0] for p in POSE]
    md.append(f"| {name} | " + " | ".join(f"{x}/20" for x in ko) + " | " + " | ".join(f"{x}/25" for x in kp) + f" | **{sum(ko)}/100** |")
md.append("")
md += ["## R7  Pooled over both seeds: frozen configuration (A) vs without width bias (E, post hoc)", "",
       "| Configuration | cracker | bottle | mug | banana | ball | **Total** |", "|---|---|---|---|---|---|---|"]
for name, rows in (("A frozen", main1 + main2), ("E no bias", nb1 + nb2)):
    ko = [ok(rows, object=o) for o in OBJ]
    k, n = ok(rows)
    md.append(f"| {name} | " + " | ".join(f"{a}/{b}" for a, b in ko) + f" | **{full(k, n)}** |")
md.append("")

prof = load("profile_150")
y = [float(r["yolo_ms"]) for r in prof]
f_ = lambda key: np.array([float(r[key]) for r in prof])
g = np.array([float(r["gng_ms"]) / float(r["n_instances"]) for r in prof])
def st(a): return f"{a.mean():.2f} | {np.median(a):.2f} | {np.percentile(a, 95):.2f}"
md += ["## R8  Latency (separate profiling run, 150 trials = 30 per object at P0, no viewer, no video)", "",
       "| Stage | mean ms | median ms | p95 ms |", "|---|---|---|---|",
       f"| RGB-D render | {st(f_('render_ms'))} |",
       f"| YOLO26s-seg (GPU), excluding the first call ({y[0]:.0f} ms) | {st(np.array(y[1:]))} |",
       f"| DBL-GNG fit (CPU), per instance | {st(g)} |",
       f"| Planner | {st(f_('plan_ms'))} |",
       f"| Sum of mean stages for one object | {np.mean(y[1:]) + g.mean() + f_('render_ms').mean() + f_('plan_ms').mean():.1f} | | |", ""]
legacy = load("abl_legacy_gng")
gl = np.array([float(r["gng_ms"]) / float(r["n_instances"]) for r in legacy if r["gng_ms"] and r["n_instances"]])
md.append(f"Earlier batch GNG fit (measured in ablation C runs): {gl.mean():.1f} ms per instance.\n")
open(OUT, "w").write("\n".join(md))
print("\n".join(md))
print(f"\nwritten: {OUT}")
